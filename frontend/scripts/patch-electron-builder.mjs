// patch-electron-builder.mjs
//
// Durable fix for electron-builder v26 on Windows + NVM-for-Windows.
//
// Problem: app-builder-lib's NpmNodeModulesCollector spawns `npm` to read the
// dependency tree, but on Windows with NVM `npm` is often not resolvable in the
// subprocess PATH, and the .cmd -> .bat -> cmd.exe wrapper chain mangles paths
// that contain spaces. The result is a build failure:
//     "No JSON content found in output"  /  MODULE_NOT_FOUND
//
// Fix: point the collector's npm path cache at a space-free .cmd shim that calls
// `node.exe npm-runner.js` with absolute paths. The shim + runner are generated
// into the Node install directory (space-free) so they survive npm installs.
//
// Idempotent and cross-platform safe: no-ops on non-Windows and when the target
// file is absent or already patched.

import { existsSync, writeFileSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

/** @param {string} msg */
function log(msg) {
  console.log(`[patch-electron-builder] ${msg}`);
}

if (process.platform !== 'win32') {
  log('non-Windows platform, nothing to do.');
  process.exit(0);
}

// 1. Locate the Node.js install directory (must contain node.exe + npm-cli.js)
const candidateNodeDirs = [
  path.dirname(process.execPath),
  'C:\\nvm4w\\nodejs',
  'C:\\Program Files\\nodejs',
];

let nodeDir = null;
let npmCli = null;
for (const dir of candidateNodeDirs) {
  const cli = path.join(dir, 'node_modules', 'npm', 'bin', 'npm-cli.js');
  if (existsSync(path.join(dir, 'node.exe')) && existsSync(cli)) {
    nodeDir = dir;
    npmCli = cli;
    break;
  }
}

if (!nodeDir) {
  log('WARNING: could not locate a Node dir with npm-cli.js; skipping patch.');
  process.exit(0);
}

const nodeExe = path.join(nodeDir, 'node.exe');

// 2. Generate eb-npm-runner.js + eb-npm-shim.cmd in the (space-free) Node dir
const runnerPath = path.join(nodeDir, 'eb-npm-runner.js');
const shimPath = path.join(nodeDir, 'eb-npm-shim.cmd');

// The generated runner is a standalone .js in the Node dir (CommonJS, not linted
// by the repo). It must use require() so npm-cli.js initializes as the main module.
const runnerContent =
  '#!/usr/bin/env node\n' +
  '// Auto-generated by patch-electron-builder.mjs - delegates to npm-cli.js.\n' +
  `process.argv[1] = ${JSON.stringify(npmCli)};\n` +
  `require(${JSON.stringify(npmCli)});\n`;

const shimContent = '@echo off\r\n' + `"${nodeExe}" "${runnerPath}" %*\r\n`;

try {
  writeFileSync(runnerPath, runnerContent, 'utf8');
  writeFileSync(shimPath, shimContent, 'utf8');
} catch (err) {
  log(`WARNING: failed to write shim/runner (${err.message}); skipping patch.`);
  process.exit(0);
}

// 3. Patch app-builder-lib's packageManager.js npm path cache
const pmFile = path.join(
  __dirname, '..', 'node_modules', 'app-builder-lib',
  'out', 'node-module-collector', 'packageManager.js'
);

if (!existsSync(pmFile)) {
  log('app-builder-lib packageManager.js not found; nothing to patch (ok).');
  process.exit(0);
}

let text = readFileSync(pmFile, 'utf8');
const shimForward = shimPath.replace(/\\/g, '/');
const patchedLine = `    [PM.NPM]: '${shimForward}',  // patched by patch-electron-builder.mjs`;

const cacheRe = /    \[PM\.NPM\]: (?:'[^']*'|undefined),(?:  \/\/.*)?/;
if (cacheRe.test(text)) {
  const before = text;
  text = text.replace(cacheRe, patchedLine);
  if (text !== before) {
    writeFileSync(pmFile, text, 'utf8');
    log(`patched packageManager.js -> PM.NPM = ${shimForward}`);
  } else {
    log('packageManager.js already patched.');
  }
} else {
  log('WARNING: PM.NPM cache line not found in packageManager.js; format may have changed.');
}

log('done.');
